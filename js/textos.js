/** Texto por clave, con reemplazo de {variables}. */
export function t(clave, vars) {
  const v = IDIOMAS[IDIOMA][clave];
  if (v === undefined) return clave;
  if (typeof v !== 'string' || !vars) return v;
  // Plural simple: {n|singular|plural} elige según vars.n === 1.
  return v.replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (_, k, uno, varios) => (Number(vars[k]) === 1 ? uno : varios)).replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

